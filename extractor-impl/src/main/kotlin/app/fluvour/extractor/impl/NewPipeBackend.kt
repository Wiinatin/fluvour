package app.fluvour.extractor.impl

import app.fluvour.extractor.api.*
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.downloader.Downloader
import org.schabi.newpipe.extractor.downloader.Request
import org.schabi.newpipe.extractor.downloader.Response
import org.schabi.newpipe.extractor.exceptions.ReCaptchaException
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.search.SearchInfo
import org.schabi.newpipe.extractor.services.youtube.linkHandler.YoutubeSearchQueryHandlerFactory
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamInfoItem

/**
 * The only class that touches NewPipeExtractor. It is compiled twice:
 *  - into the app, as the built-in fallback (version pinned in gradle.properties);
 *  - into the plugin APK, built by CI from the newest NewPipeExtractor release and downloaded by the app.
 * Needs a public no-argument constructor: the app creates it by name.
 */
class NewPipeBackend : ExtractorBackend {
    override val apiVersion: Int = ExtractorApi.VERSION
    override val extractorVersion: String = NEWPIPE_VERSION

    override fun init(fetcher: HttpFetcher) { NewPipe.init(FetcherDownloader(fetcher)) }

    override fun extract(url: String): ExtractedMedia {
        val info = StreamInfo.getInfo(url)
        return ExtractedMedia(
            title = info.name ?: "",
            uploader = info.uploaderName,
            videoStreams = info.videoStreams.map { VideoStream(it.content, it.height, it.isVideoOnly) },
            audioStreams = info.audioStreams.filter { it.isUrl }.map { AudioStream(it.content, it.format?.suffix, it.averageBitrate) },
            subtitles = info.subtitles.map { SubtitleTrack(it.languageTag, it.format?.suffix, it.isAutoGenerated, it.content) },
            durationSeconds = info.duration,
            thumbnails = runCatching { info.thumbnails.map { Thumbnail(it.url, it.height) } }.getOrDefault(emptyList())
        )
    }

    override fun search(query: String): List<SearchHit> {
        val service = ServiceList.YouTube
        val handler = service.searchQHFactory.fromQuery(query.trim(), listOf(YoutubeSearchQueryHandlerFactory.VIDEOS), "")
        val info = SearchInfo.getInfo(service, handler)
        return info.relatedItems.filterIsInstance<StreamInfoItem>().map { v ->
            SearchHit(v.url, v.name, v.uploaderName, v.duration,
                runCatching { v.thumbnails.map { Thumbnail(it.url, it.height) } }.getOrDefault(emptyList()))
        }
    }
}

private class FetcherDownloader(private val fetcher: HttpFetcher) : Downloader() {
    override fun execute(request: Request): Response {
        val r = fetcher.execute(HttpRequest(request.httpMethod(), request.url(), request.headers(), request.dataToSend()))
        if (r.code == 429) throw ReCaptchaException("YouTube asked for a captcha", request.url())
        return Response(r.code, r.message, r.headers, r.body, r.finalUrl)
    }
}
